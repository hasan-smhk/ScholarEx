import { useEffect, useState } from 'react';
import { Link, Navigate } from 'react-router-dom';
import { ArrowLeft, Download, Loader2, Mail, RefreshCw } from 'lucide-react';
import { getMyCareerAssessment, resendMyCareerReport, StudentCareerAssessment } from '../services/api';
import { useAuth } from '../context/AuthContext';

const reportSections = [
  ['Strengths', 'strengths'],
  ['Development areas', 'developmentAreas'],
  ['Interests', 'interests'],
  ['Career directions to explore', 'careerDirectionsToExplore'],
  ['Stream options to discuss', 'streamOptionsToDiscuss'],
  ['Counselling action plan', 'counselingActionPlan'],
] as const;

export default function StudentCareerReportPage() {
  const { user, token } = useAuth();
  const [assessment, setAssessment] = useState<StudentCareerAssessment | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [retryingEmail, setRetryingEmail] = useState(false);
  const [emailMessage, setEmailMessage] = useState('');

  useEffect(() => {
    if (!token) return;
    let active = true;
    getMyCareerAssessment(token)
      .then(({ data }) => {
        if (active) setAssessment(data);
      })
      .catch((requestError: any) => {
        if (active) setError(requestError.response?.data?.error || 'Could not load your report.');
      })
      .finally(() => {
        if (active) setLoading(false);
      });
    return () => {
      active = false;
    };
  }, [token]);

  const resendEmail = async () => {
    if (!token || retryingEmail) return;
    setRetryingEmail(true);
    setEmailMessage('');
    try {
      await resendMyCareerReport(token);
      setAssessment((current) => current ? { ...current, reportEmailSentAt: new Date().toISOString() } : current);
      setEmailMessage('The report email was sent.');
    } catch (requestError: any) {
      setEmailMessage(requestError.response?.data?.error || 'Could not send the report email. Please try again.');
    } finally {
      setRetryingEmail(false);
    }
  };

  if (user?.role !== 'STUDENT') return <Navigate to="/dashboard" replace />;
  if (loading) return <main className="flex min-h-[65vh] items-center justify-center"><Loader2 className="h-10 w-10 animate-spin text-teal-700" /></main>;
  if (error) return <main className="mx-auto max-w-3xl px-5 py-16"><p role="alert" className="rounded-xl bg-red-50 p-5 text-red-800">{error}</p></main>;
  if (!assessment?.report) return <Navigate to="/counseling" replace />;

  return (
    <main className="scholar-page min-h-screen px-5 py-10 print:bg-white print:px-0 print:py-0">
      <div className="mx-auto max-w-5xl">
        <div className="mb-6 flex flex-wrap items-center justify-between gap-3 print:hidden">
          <Link to="/dashboard" className="inline-flex items-center gap-2 font-semibold text-teal-800 hover:text-teal-600">
            <ArrowLeft className="h-4 w-4" /> Back to dashboard
          </Link>
          <button type="button" onClick={() => window.print()} className="inline-flex items-center gap-2 rounded-xl bg-teal-800 px-4 py-2.5 font-bold text-white hover:bg-teal-900">
            <Download className="h-4 w-4" /> Download / print PDF
          </button>
        </div>

        <article className="rounded-3xl border border-slate-200 bg-white p-6 shadow-sm sm:p-10 print:border-0 print:shadow-none">
          <header className="flex flex-wrap items-center justify-between gap-4 border-b border-slate-200 pb-6">
            <img src="/scholarex-logo.png" alt="ScholarEx" className="h-auto w-44" />
            <div className="text-right">
              <p className="text-xs font-bold uppercase tracking-widest text-teal-700">Free AI career guidance report</p>
              <h1 className="mt-1 text-2xl font-black text-slate-900">{user?.name}</h1>
              <p className="text-sm text-slate-600">{assessment.studentClass} · {assessment.educationBoard}</p>
            </div>
          </header>

          <p className="mt-5 rounded-xl bg-teal-50 p-4 text-sm leading-6 text-teal-950">
            This report is a starting point for discussion and exploration. Career directions and stream options are not prescriptions; confirm subject eligibility and requirements with your school.
          </p>

          <div className="mt-6 grid gap-5 md:grid-cols-2">
            {reportSections.map(([title, field]) => (
              <section key={field} className="break-inside-avoid rounded-2xl border border-slate-100 bg-slate-50 p-5">
                <h2 className="font-black text-teal-800">{title}</h2>
                <p className="mt-2 whitespace-pre-wrap text-sm leading-6 text-slate-700">{assessment.report![field]}</p>
              </section>
            ))}
          </div>

          <footer className="mt-8 border-t border-slate-200 pt-5 text-xs leading-5 text-slate-500">
            Generated by ScholarEx from the information provided by the student. No psychometric or aptitude scores were supplied for this report.
          </footer>
        </article>

        <section className="mt-6 rounded-2xl border border-slate-200 bg-white p-5 print:hidden">
          <div className="flex flex-wrap items-center justify-between gap-4">
            <div className="flex items-start gap-3">
              <Mail className="mt-1 h-5 w-5 text-teal-700" />
              <div>
                <h2 className="font-bold text-slate-900">Report email</h2>
                <p className="text-sm text-slate-600">
                  {assessment.reportEmailSentAt ? 'Sent to your account email.' : 'The report is ready, but the email has not been delivered.'}
                </p>
                {emailMessage && <p role="status" className="mt-1 text-sm text-teal-800">{emailMessage}</p>}
              </div>
            </div>
            <button type="button" onClick={resendEmail} disabled={retryingEmail} className="inline-flex items-center gap-2 rounded-xl border border-teal-700 px-4 py-2.5 font-bold text-teal-800 hover:bg-teal-50 disabled:opacity-50">
              {retryingEmail ? <Loader2 className="h-4 w-4 animate-spin" /> : <RefreshCw className="h-4 w-4" />}
              Send report email
            </button>
          </div>
        </section>

        <section className="mt-6 flex flex-col gap-4 rounded-2xl bg-indigo-950 p-6 text-white sm:flex-row sm:items-center sm:justify-between print:hidden">
          <div>
            <h2 className="text-xl font-black">Ready for one-to-one guidance?</h2>
            <p className="mt-1 text-sm text-indigo-100">Choose a counselor and pay to reserve a counseling session.</p>
          </div>
          <Link to="/counselors" className="inline-flex shrink-0 items-center justify-center rounded-xl bg-white px-5 py-3 font-bold text-indigo-900 hover:bg-indigo-50">
            Book a paid counseling slot
          </Link>
        </section>
      </div>
      <style>{'@media print { nav { display: none !important; } body { background: white !important; } }'}</style>
    </main>
  );
}
